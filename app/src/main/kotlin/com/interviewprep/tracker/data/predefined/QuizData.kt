    fun getQuestions(topic: QuizTopic, difficulty: QuizDifficulty, count: Int = 10): List<QuizQuestion> {
        return allQuestions
            .filter { it.topic == topic && it.difficulty == difficulty }
            .shuffled()
            .take(count)
            .ifEmpty {
                // Fallback: return questions from the topic regardless of difficulty
                allQuestions.filter { it.topic == topic }.shuffled().take(count)
            }
    }

    fun getAllTopics(): List<QuizTopic> = QuizTopic.values().toList()

    fun getAllDifficulties(): List<QuizDifficulty> = QuizDifficulty.values().toList()

    fun getQuestionCountByTopic(topic: QuizTopic): Map<QuizDifficulty, Int> {
        return QuizDifficulty.values().associateWith { difficulty ->
            allQuestions.count { it.topic == topic && it.difficulty == difficulty }
        }
    }
